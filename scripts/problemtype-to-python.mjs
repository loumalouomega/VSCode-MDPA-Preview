#!/usr/bin/env node
// Prints the DECLARATION half of a built-in problemtype as Python source for
// the example ports in example/problemtypes/ (the sections, conditions,
// material laws, coupled domains and the define_problemtype() arguments), so a port's
// declaration cannot drift from the TypeScript original. The hooks
// (solver_settings / build_process / post_process) are not translated: they
// are hand-ported, and src/test/problemtypeExamples.test.ts asserts the result
// generates byte-identical case files.
//
// Usage (after `npm run build:tests`):
//   node scripts/problemtype-to-python.mjs structural > /tmp/structural_decl.py
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const { BUILTIN_PROBLEMTYPES } = require(path.join(ROOT, "out", "problemtype", "builtins", "index.js"));

const id = process.argv[2];
const runtime = BUILTIN_PROBLEMTYPES.find((p) => p.decl.id === id);
if (!runtime) {
  console.error(`unknown built-in "${id}"; one of: ${BUILTIN_PROBLEMTYPES.map((p) => p.decl.id).join(", ")}`);
  process.exit(1);
}
const decl = runtime.decl;

/** A JSON value as Python source. */
function py(v, indent = 0) {
  if (v === null || v === undefined) return "None";
  if (v === true) return "True";
  if (v === false) return "False";
  if (typeof v === "number") return Number.isInteger(v) && Math.abs(v) < 1e15 ? String(v) : String(v).replace("e+", "e+");
  if (typeof v === "string") return JSON.stringify(v);
  if (Array.isArray(v)) return `[${v.map((x) => py(x, indent)).join(", ")}]`;
  const pad = " ".repeat(indent + 4);
  const entries = Object.entries(v).map(([k, x]) => `${pad}${JSON.stringify(k)}: ${py(x, indent + 4)},`);
  return `{\n${entries.join("\n")}\n${" ".repeat(indent)}}`;
}

function ruleSrc(r) {
  const kv = [`"field": ${JSON.stringify(r.field)}`];
  if (r.equals !== undefined) kv.push(`"equals": ${py(r.equals)}`);
  else kv.push(`"one_of": ${py(r.oneOf)}`);
  return `{${kv.join(", ")}}`;
}

/** A single visible/when rule, or a list meaning "all must hold". */
function whenSrc(when) {
  return Array.isArray(when) ? `[${when.map(ruleSrc).join(", ")}]` : ruleSrc(when);
}

function fieldSrc(f, indent) {
  const pad = " ".repeat(indent);
  const args = [JSON.stringify(f.id), JSON.stringify(f.label), JSON.stringify(f.type)];
  if (f.default !== undefined) args.push(`default=${py(f.default)}`);
  if (f.options) {
    const opts = f.options.map((o) => (o.label !== undefined ? `{"value": ${JSON.stringify(o.value)}, "label": ${JSON.stringify(o.label)}}` : JSON.stringify(o.value)));
    args.push(`options=[${opts.join(", ")}]`);
  }
  if (f.visibleWhen !== undefined) {
    args.push(`visible_when=${whenSrc(f.visibleWhen)}`);
  }
  if (f.unit !== undefined) args.push(`unit=${JSON.stringify(f.unit)}`);
  if (f.help !== undefined) args.push(`help=${JSON.stringify(f.help)}`);
  if (f.group !== undefined) args.push(`group=${JSON.stringify(f.group)}`);
  for (const k of ["min", "max", "step"]) if (f[k] !== undefined) args.push(`${k}=${py(f[k])}`);
  if (f.advanced !== undefined) args.push(`advanced=${py(f.advanced)}`);
  return `${pad}field(${args.join(", ")})`;
}

const out = [];
out.push(`# --- declaration of "${decl.id}" generated by scripts/problemtype-to-python.mjs ---`);
decl.sections.forEach((s, i) => {
  out.push(`SECTION_${i} = section(${JSON.stringify(s.id)}, ${JSON.stringify(s.label)},`);
  s.fields.forEach((f, j) => out.push(`${fieldSrc(f, 4)}${j === s.fields.length - 1 && !s.groups && !s.icon ? ")" : ","}`));
  const tail = [];
  if (s.groups) {
    const g = s.groups.map((x) => {
      const a = [JSON.stringify(x.id), JSON.stringify(x.label)];
      if (x.icon) a.push(`icon=${JSON.stringify(x.icon)}`);
      if (x.collapsed !== undefined) a.push(`collapsed=${py(x.collapsed)}`);
      return `field_group(${a.join(", ")})`;
    });
    tail.push(`    groups=[${g.join(", ")}]`);
  }
  if (s.icon) tail.push(`    icon=${JSON.stringify(s.icon)}`);
  if (tail.length) out.push(`${tail.join(",\n")})`);
  out.push("");
});
out.push("CONDITIONS = [");
for (const c of decl.conditions) {
  const a = [JSON.stringify(c.id), JSON.stringify(c.label), `list=${JSON.stringify(c.list)}`, `target=${JSON.stringify(c.target)}`];
  out.push(`    condition(${a.join(", ")},`);
  out.push(`              fields=[${c.fields.map((f) => fieldSrc(f, 0)).join(",\n                      ")}],`);
  out.push(`              process_template=${py(c.processTemplate, 14)}${c.help || c.category || c.icon || c.noProcess ? "," : ")"}`);
  const rest = [];
  if (c.help !== undefined) rest.push(`help=${JSON.stringify(c.help)}`);
  if (c.category !== undefined) rest.push(`category=${JSON.stringify(c.category)}`);
  if (c.icon !== undefined) rest.push(`icon=${JSON.stringify(c.icon)}`);
  if (c.noProcess) rest.push("no_process=True");
  if (c.emit !== undefined) rest.push(`emit=${JSON.stringify(c.emit)}`);
  if (rest.length) out.push(`              ${rest.join(", ")}),`);
  else out.push("              ),");
}
out.push("]");
out.push("");
out.push("MATERIAL_LAWS = [");
for (const l of decl.materialLaws) {
  const a = [JSON.stringify(l.id), JSON.stringify(l.name)];
  const extra = [];
  if (l.application) extra.push(`application=${JSON.stringify(l.application)}`);
  if (l.group) extra.push(`group=${JSON.stringify(l.group)}`);
  if (l.parameters) extra.push(`parameters=${py(l.parameters, 17)}`);
  if (l.when) extra.push(`when=${whenSrc(l.when)}`);
  if (l.domainSize) extra.push(`domain_size=${l.domainSize}`);
  if (l.domain) extra.push(`domain=${JSON.stringify(l.domain)}`);
  out.push(`    material_law(${a.join(", ")},`);
  out.push(`                 variables=[${l.variables.map((f) => fieldSrc(f, 0)).join(",\n                            ")}]${extra.length ? ",\n                 " + extra.join(",\n                 ") : ""}),`);
}
out.push("]");
out.push("");
if (decl.domains) {
  out.push("DOMAINS = [");
  for (const d of decl.domains) {
    const a = [JSON.stringify(d.id), JSON.stringify(d.label), JSON.stringify(d.modelPartName), JSON.stringify(d.mdpaSuffix), JSON.stringify(d.partsCondition)];
    out.push(`    domain(${a.join(", ")},`);
    out.push(`           condition_ids=${py(d.conditionIds)},`);
    const rest = [];
    if (d.materialsFileName !== undefined) rest.push(`           materials_file_name=${JSON.stringify(d.materialsFileName)}`);
    if (d.required) rest.push(`           required=${py(d.required, 11)}`);
    if (d.meshNaming) rest.push(`           mesh_naming=${py(d.meshNaming, 11)}`);
    if (d.pointLoadInterface) rest.push(`           point_load_interface=${py(d.pointLoadInterface, 11)}`);
    out.push(`${rest.join(",\n")}),`);
  }
  out.push("]");
  out.push("");
}
const meta = {
  description: decl.description,
  icon: decl.icon,
  family: decl.family,
  analysis_stage: decl.analysisStage,
  model_part_name: decl.modelPartName,
  materials_file_name: decl.materialsFileName,
  domain_sizes: decl.domainSizes,
  parts_condition: decl.partsCondition,
  mesh_naming: decl.meshNaming,
  applications: decl.applications,
  coupling_interfaces: decl.couplingInterfaces,
  primary_document_name: decl.primaryDocumentName,
  driver_script_name: decl.driverScriptName,
  driver_template: decl.driverTemplate,
  output: { nodal_defaults: decl.output.nodalDefaults, ...(decl.output.gaussDefaults ? { gauss_defaults: decl.output.gaussDefaults } : {}) },
};
out.push("# define_problemtype(...) arguments:");
for (const [k, v] of Object.entries(meta)) if (v !== undefined) out.push(`#   ${k}=${py(v, 0).replace(/\n/g, "\n#   ")},`);
console.log(out.join("\n"));
