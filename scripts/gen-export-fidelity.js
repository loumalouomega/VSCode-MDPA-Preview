#!/usr/bin/env node
// Regenerates src/parser/exportFidelityTable.ts from a live measurement: every
// writer is run against the reference model of src/test/exportReportMatrix.ts,
// re-read, and graded. Needs a test build first (`npm run build:tests`).
// exportReport.test.ts fails when the committed table stops matching the
// measurement, so a kernel bump that changes a writer shows up as a diff here.
"use strict";
const fs = require("node:fs");
const path = require("node:path");

const root = path.resolve(__dirname, "..");
const { measureAll } = require(path.join(root, "out/test/exportReportMatrix.js"));

const HEADER = `// GENERATED by scripts/gen-export-fidelity.js — do not edit by hand.
// One entry per writer key (native writers by extension), measured by writing
// the reference model of src/test/exportReportMatrix.ts and re-reading it.
// Codes: r = retained, t = transformed, o = omitted. \`fields\` is keyed
// "<kind>:<components>". \`unmeasured\` names why the reference mesh could not
// be round-tripped, and the report then says "unverified" instead of guessing.
// exportReport.test.ts fails when this file stops matching a fresh measurement.

export type Code = "r" | "t" | "o";

export interface MeasuredRow {
  base: Partial<Record<string, Code>>;
  fields: Record<string, Code>;
}

export type MeasuredEntry = MeasuredRow | { unmeasured: string };

/** VTK cell types the reference mesh contains (hexahedron, quad); claims about other types are unverified. */
export const MEASURED_CELL_TYPES: readonly number[] = [9, 12];

export const EXPORT_FIDELITY_TABLE: Readonly<Record<string, MeasuredEntry>> = `;

measureAll().then((table) => {
  const lines = ["{"];
  for (const [key, entry] of Object.entries(table)) {
    lines.push(`  ${JSON.stringify(key)}: ${JSON.stringify(entry)},`);
  }
  lines.push("};", "");
  fs.writeFileSync(path.join(root, "src/parser/exportFidelityTable.ts"), HEADER + lines.join("\n"));
  console.log(`wrote ${Object.keys(table).length} entries`);
});
