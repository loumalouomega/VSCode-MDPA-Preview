// Regenerates src/parser/colormapPresets.ts from the ParaView presets vtk.js
// ships (Rendering/Core/ColorTransferFunction/ColorMaps), resampled through
// vtk.js's own colour transfer function (so the Diverging/Lab colour spaces of
// a preset are evaluated, not approximated by its few control points) onto
// STOPS evenly spaced stops. Only a curated list is kept: the whole library is
// 190 entries, most of them neither perceptually ordered nor useful for FE
// results. Colour-blind safety is NOT taken from vtk.js (it records none): the
// flag is set only for maps whose published source (ColorBrewer's "colourblind
// safe" rating, or the matplotlib family) says so.
//
//   node scripts/gen-colormap-presets.mjs
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import * as path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const presets = (await import("@kitware/vtk.js/Rendering/Core/ColorTransferFunction/ColorMaps.json.js")).default;
const vtkCTF = (await import("@kitware/vtk.js/Rendering/Core/ColorTransferFunction.js")).default;
const list = Array.isArray(presets) ? presets : Object.values(presets);
const STOPS = 17;

// [vtk preset name, display name, category, colour-blind safe]
const CURATED = [
  ["Cool to Warm", "Cool to Warm", "diverging", true],
  ["Cool to Warm (Extended)", "Cool to Warm (Extended)", "diverging", true],
  ["Brewer Diverging Purple-Orange (11)", "Purple-Orange", "diverging", true],
  ["Brewer Diverging Brown-Blue-Green (11)", "Brown-Blue-Green", "diverging", true],
  ["Brewer Diverging Spectral (11)", "Brewer Spectral", "diverging", false],
  ["erdc_iceFire_H", "Ice-Fire", "diverging", true],
  ["erdc_divHi_purpleGreen", "Purple-Green (high contrast)", "diverging", true],
  ["erdc_divLow_icePeach", "Ice-Peach", "diverging", true],
  ["Black-Body Radiation", "Black-Body", "sequential", true],
  ["Brewer Sequential Blue-Green (9)", "Blue-Green", "sequential", true],
  ["Brewer Sequential Blue-Purple (9)", "Blue-Purple", "sequential", true],
  ["Brewer Sequential Yellow-Orange-Brown (9)", "Yellow-Orange-Brown", "sequential", true],
  ["Blues", "Blues", "sequential", true],
  ["Greens", "Greens", "sequential", true],
  ["Oranges", "Oranges", "sequential", true],
  ["Purples", "Purples", "sequential", true],
  ["Reds", "Reds", "sequential", true],
  ["erdc_blue2gold_BW", "Blue to Gold", "sequential", true],
  ["erdc_sapphire2gold_BW", "Sapphire to Gold", "sequential", true],
  ["Haze", "Haze", "sequential", false],
  ["X Ray", "X-Ray", "sequential", true],
  ["heated_object", "Heated Object", "sequential", true],
  ["gist_earth", "Earth", "sequential", false],
  ["Rainbow Desaturated", "Rainbow Desaturated", "rainbow", false],
  ["erdc_rainbow_bright", "Rainbow Bright", "rainbow", false],
  ["erdc_rainbow_dark", "Rainbow Dark", "rainbow", false],
  ["Linear YGB 1211g", "Yellow-Green-Blue", "sequential", true],
];

const out = [];
for (const [vtkName, name, category, colorblindSafe] of CURATED) {
  const preset = list.find((p) => p.Name === vtkName);
  if (!preset) throw new Error(`vtk.js has no preset "${vtkName}"`);
  const stops = [];
  if (preset.RGBPoints) {
    const ctf = vtkCTF.newInstance();
    ctf.applyColorMap(preset);
    const range = ctf.getRange();
    const rgb = [0, 0, 0];
    for (let i = 0; i < STOPS; i++) {
      const t = i / (STOPS - 1);
      ctf.getColor(range[0] + t * (range[1] - range[0]), rgb);
      stops.push([+t.toFixed(4), ...rgb.map((v) => +v.toFixed(3))]);
    }
  } else if (preset.IndexedColors) {
    // A ColorBrewer ramp is published as N discrete colours; used as a
    // continuous map they are evenly spaced control points.
    const c = preset.IndexedColors;
    const n = c.length / 3;
    for (let i = 0; i < STOPS; i++) {
      const t = i / (STOPS - 1);
      const x = t * (n - 1);
      const k = Math.min(n - 2, Math.floor(x));
      const f = x - k;
      stops.push([+t.toFixed(4), ...[0, 1, 2].map((j) => +(c[k * 3 + j] * (1 - f) + c[(k + 1) * 3 + j] * f).toFixed(3))]);
    }
  } else {
    throw new Error(`preset "${vtkName}" has neither RGBPoints nor IndexedColors`);
  }
  out.push({ name, category, colorblindSafe, source: vtkName, stops });
}

const body = out
  .map(
    (c) =>
      `  { name: ${JSON.stringify(c.name)}, category: ${JSON.stringify(c.category)}, colorblindSafe: ${c.colorblindSafe}, source: ${JSON.stringify(c.source)}, stops: ${JSON.stringify(c.stops)} },`
  )
  .join("\n");
writeFileSync(
  path.join(ROOT, "src/parser/colormapPresets.ts"),
  `// GENERATED by scripts/gen-colormap-presets.mjs — do not edit by hand.
// Curated presets from vtk.js 's ParaView colour map library, ${STOPS} stops each.

export type ColormapCategory = "diverging" | "sequential" | "rainbow";

export interface ColormapPreset {
  name: string;
  category: ColormapCategory;
  /** True only where the map's published source rates it colour-blind safe. */
  colorblindSafe: boolean;
  /** The vtk.js / ParaView preset it was resampled from. */
  source: string;
  stops: [number, number, number, number][];
}

export const COLORMAP_PRESETS: ColormapPreset[] = [
${body}
];
`
);
console.log(`wrote ${out.length} presets`);
